#!/usr/bin/env bash
# Create a self-signed code-signing certificate for local Niagara development.
# Writes only under security/, which is gitignored except for the example templates.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SEC="$ROOT/security"
mkdir -p "$SEC"

ALIAS="${NIAGARA_SIGNING_ALIAS:-controlbasic}"
STORE_PASS="${NIAGARA_SIGNING_STORE_PASSWORD:-}"
KEY_PASS="${NIAGARA_SIGNING_KEY_PASSWORD:-$STORE_PASS}"
DNAME="${NIAGARA_SIGNING_DNAME:-CN=Control Basic Dev, OU=Development, O=Local, C=US}"
KEYSTORE="${NIAGARA_SIGNING_KEYSTORE:-$SEC/dev-keystore.p12}"
CERT="$SEC/dev-cert.cer"
PROPS="$SEC/niagara.signing.properties"
XML="$SEC/niagara.signing.xml"
DAYS="${NIAGARA_SIGNING_DAYS:-3650}"

if [[ -z "$STORE_PASS" ]]; then
  echo "Set NIAGARA_SIGNING_STORE_PASSWORD before running this script." >&2
  exit 1
fi
if [[ -z "$KEY_PASS" ]]; then
  KEY_PASS="$STORE_PASS"
fi

if [[ -e "$KEYSTORE" ]]; then
  echo "Keystore already exists: $KEYSTORE" >&2
  echo "Delete it first if you intend to replace it." >&2
  exit 1
fi

keytool -genkeypair \
  -alias "$ALIAS" \
  -keyalg RSA \
  -keysize 2048 \
  -sigalg SHA256withRSA \
  -validity "$DAYS" \
  -storetype PKCS12 \
  -keystore "$KEYSTORE" \
  -storepass "$STORE_PASS" \
  -keypass "$KEY_PASS" \
  -dname "$DNAME" \
  -ext "BasicConstraints=ca:false" \
  -ext "KeyUsage=digitalSignature" \
  -ext "ExtendedKeyUsage=codeSigning"

keytool -exportcert \
  -alias "$ALIAS" \
  -keystore "$KEYSTORE" \
  -storetype PKCS12 \
  -storepass "$STORE_PASS" \
  -rfc \
  -file "$CERT"

# Absolute path so Gradle resolves the keystore no matter the working directory.
ABS_KEYSTORE="$(cd "$(dirname "$KEYSTORE")" && pwd)/$(basename "$KEYSTORE")"

cat > "$PROPS" <<EOF
# Generated by scripts/generate-dev-cert.sh. Gitignored. Do not commit.
alias=$ALIAS
keystoreType=PKCS12
keystoreFile=$ABS_KEYSTORE
storePassword=$STORE_PASS
keyPassword=$KEY_PASS
timestampUrl=http://timestamp.digicert.com
EOF

cat > "$XML" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-dev-cert.sh. Gitignored. Do not commit. -->
<signingProfile>
  <className>com.tridium.gradle.plugins.signing.profile.RestrictedSigningProfile</className>
  <alias>$ALIAS</alias>
  <keystoreType>PKCS12</keystoreType>
  <keystoreFile>$ABS_KEYSTORE</keystoreFile>
  <storePassword>$STORE_PASS</storePassword>
  <keyPassword>$KEY_PASS</keyPassword>
  <timestampUrl>http://timestamp.digicert.com</timestampUrl>
</signingProfile>
EOF

chmod 600 "$KEYSTORE" "$PROPS" "$XML" || true

echo "Wrote:"
echo "  $ABS_KEYSTORE"
echo "  $CERT"
echo "  $PROPS"
echo "  $XML"
echo
echo "Point local.properties at the profile:"
echo "  certAlias=$ALIAS"
echo "  niagara.signing.profile=$XML"
echo
echo "If the Niagara signing plugin rejects that XML, use the properties file"
echo "or generate a plugin-native profile. See docs/SIGNING.md."
echo "Import $CERT into the Workbench User Trust Store before loading the module."
