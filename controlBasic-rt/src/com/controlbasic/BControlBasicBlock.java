  private void syncAlarmLocked() {
    if (!isRunning() || !Sys.atSteadyState()) {
      return;
    }
    final String fault = health.fault();
    if (fault == null ? alarmedFault == null : fault.equals(alarmedFault)) {
      return;
    }
    final String previous = alarmedFault;
    alarmedFault = fault;
    final AlarmSupport support = alarmSupport();
    Throwable problem = AccessController.doPrivileged(new PrivilegedAction<Throwable>() {
      @Override
      public Throwable run() {
        try {
          if (previous != null) {
            support.toNormal(BFacets.make(BAlarmRecord.MSG_TEXT, "Cleared: " + previous), null);
          }
          if (fault != null) {
            support.newFaultAlarm(BFacets.make(BAlarmRecord.MSG_TEXT, fault));
          }
          return null;
        } catch (Throwable ex) {
          return ex;
        }
      }
    });
    if (problem != null) {
      LOG.log(Level.WARNING, "Control Basic " + where() + ": could not route the fault alarm", problem);
      return;
    }
    String alarmClass = getAlarmSourceInfo().getAlarmClass();
    if (fault != null) {
      LOG.info("Control Basic " + where() + ": fault alarm sent to " + alarmClass + ": " + fault);
    } else {
      LOG.info("Control Basic " + where() + ": fault alarm returned to normal in " + alarmClass);
    }
  }

