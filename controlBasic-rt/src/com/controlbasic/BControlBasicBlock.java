  private static void loadTable(RuntimeState state, int index, String text) {
    if (text == null || text.trim().length() == 0) {
      state.setTable(index, null, null);
      return;
    }
    String[] pairs = text.split("[;\\n]+");
    double[] xs = new double[pairs.length];
    double[] ys = new double[pairs.length];
    int n = 0;
    for (int i = 0; i < pairs.length; i++) {
      String pair = pairs[i].trim();
      if (pair.length() == 0) {
        continue;
      }
      String[] parts = pair.split("[,\\s]+");
      if (parts.length < 2) {
        continue;
      }
      xs[n] = Double.parseDouble(parts[0].trim());
      ys[n] = Double.parseDouble(parts[1].trim());
      n++;
    }
    if (n == 0) {
      state.setTable(index, null, null);
      return;
    }
    double[] xTrim = new double[n];
    double[] yTrim = new double[n];
    System.arraycopy(xs, 0, xTrim, 0, n);
    System.arraycopy(ys, 0, yTrim, 0, n);
    state.setTable(index, xTrim, yTrim);
  }

