  @Override
  protected void doLoadValue(BObject value, Context cx) throws Exception {
    super.doLoadValue(value, cx);
    if (!(value instanceof BControlBasicBlock)) {
      return;
    }
    block = (BControlBasicBlock) value;
    editor.setText(block.getProgram() == null ? "" : block.getProgram());
    lint(false);
  }

  void save() {
    if (block == null) {
      status.setText("No component loaded");
      return;
    }
    block.setProgram(editor.getText() == null ? "" : editor.getText());
    lint(true);
  }

  void lint(boolean saved) {
    String text = editor.getText() == null ? "" : editor.getText();
    refreshGutter(text);
    Compilation compilation = ControlBasic.compile(text);
    if (!compilation.ok()) {
      Diagnostic diagnostic = compilation.diagnostics().get(0);
      syntax.setErrorLine(diagnostic.line);
      status.setText(diagnostic.format());
      editor.repaint();
      return;
    }
    syntax.setErrorLine(-1);
    StringBuilder ok = new StringBuilder();
    ok.append(saved ? "Saved. " : "OK. ");
    ok.append(compilation.slots().size()).append(" slots");
    if (!compilation.slots().isEmpty()) {
      ok.append(": ");
      for (int i = 0; i < compilation.slots().size(); i++) {
        SlotSpec spec = compilation.slots().get(i);
        if (i > 0) {
          ok.append(", ");
        }
        ok.append(spec.name);
      }
    }
    if (block != null && block.getLastError() != null && block.getLastError().length() > 0 && saved) {
      ok.append(" — ").append(block.getLastError());
    }
    status.setText(ok.toString());
    editor.repaint();
  }

  private void refreshGutter(String text) {
    int lines = 1;
    for (int i = 0; i < text.length(); i++) {
      if (text.charAt(i) == '\n') {
        lines++;
      }
    }
    StringBuilder numbers = new StringBuilder();
    for (int i = 1; i <= lines; i++) {
      if (i > 1) {
        numbers.append('\n');
      }
      numbers.append(i);
    }
    gutter.setText(numbers.toString());
  }

